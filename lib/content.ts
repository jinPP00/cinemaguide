/** 시도별 목록 페이지 인트로 — 지역마다 다른 문장이 나오도록 데이터 기반으로 구성 */
export function sidoIntro(
  brandName: string,
  sido: string,
  count: number,
  specialCount: number,
  cityCount: number,
): string {
  const parts: string[] = [];

  parts.push(
    `${sido} 지역에는 ${brandName} 지점이 ${count}곳 있습니다.` +
      (cityCount > 1 ? ` ${cityCount}개 시·군·구에 나뉘어 분포합니다.` : ''),
  );

  if (specialCount > 0) {
    parts.push(
      `이 중 ${specialCount}곳은 특별관을 함께 운영하고 있어, 상영관 종류에 따라 관람료가 달라집니다.`,
    );
  }

  parts.push(
    '각 지점 페이지에서 상영시간표 바로가기와 함께 주소, 대중교통 이용 방법, 주차 조건, 관람료를 확인할 수 있습니다.',
  );

  return parts.join(' ');
}
